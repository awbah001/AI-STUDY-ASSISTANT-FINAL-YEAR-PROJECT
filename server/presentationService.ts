import fs from "fs";
import path from "path";
import { TRPCError } from "@trpc/server";
import PptxGenJS from "pptxgenjs";
import { canAccessDocument } from "./documentAccess";
import * as documentAi from "./documentAiService";
import { generateSlideDeck, type SlideDeck } from "./llmUtils";
import * as queries from "./queries";
import type { GeneratedSlides } from "../drizzle/schema";
import { getFeatureFlags } from "./settings";
import { resolveUploadPath } from "./_core/uploads";

const inFlight = new Map<number, Promise<GeneratedSlides>>();

async function assertAccess(userId: number, documentId: number) {
  const doc = await queries.getDocumentById(documentId);
  if (!doc || !(await canAccessDocument(userId, doc)))
    throw new TRPCError({ code: "NOT_FOUND" });
  return doc;
}

/** Build a .pptx Buffer from a generated slide deck. */
function buildPptxBuffer(deck: SlideDeck): Promise<Buffer> {
  const pptx = new PptxGenJS();
  pptx.defineLayout({ name: "WIDE", width: 13.333, height: 7.5 });
  pptx.layout = "WIDE";
  pptx.author = "AI Learning Assistant";
  pptx.company = "AI Learning Assistant";
  pptx.subject = deck.title;
  pptx.title = deck.title;

  // Title slide.
  const titleSlide = pptx.addSlide();
  titleSlide.background = { color: "1E3A5F" };
  titleSlide.addText(deck.title, {
    x: 0.6, y: 2.6, w: 12.1, h: 1.6,
    fontSize: 40, bold: true, color: "FFFFFF", align: "center", fontFace: "Arial",
  });
  if (deck.subtitle) {
    titleSlide.addText(deck.subtitle, {
      x: 0.6, y: 4.2, w: 12.1, h: 1,
      fontSize: 22, color: "B9D3EA", align: "center", fontFace: "Arial",
    });
  }
  titleSlide.addText("Generated by the AI Learning Assistant", {
    x: 0.6, y: 6.7, w: 12.1, h: 0.5,
    fontSize: 12, color: "8FB3D4", align: "center", italic: true,
  });

  // Content slides.
  for (const slide of deck.slides) {
    const s = pptx.addSlide();
    s.background = { color: "FFFFFF" };
    s.addText(slide.title, {
      x: 0.6, y: 0.4, w: 12.1, h: 0.9,
      fontSize: 28, bold: true, color: "1E3A5F", fontFace: "Arial",
    });
    s.addShape(pptx.ShapeType.line, { x: 0.7, y: 1.3, w: 11.9, h: 0, line: { color: "1E3A5F", width: 2 } });
    s.addText(
      slide.bullets.map((b) => ({ text: b, options: { bullet: true as const, indentLevel: 0 } })),
      {
        x: 0.7, y: 1.55, w: 11.9, h: 5.4,
        fontSize: 18, color: "333333", fontFace: "Arial",
        lineSpacingMultiple: 1.25, valign: "top",
      }
    );
    if (slide.notes) s.addNotes(slide.notes);
  }

  return pptx.write({ outputType: "nodebuffer" }).then((out) =>
    Buffer.isBuffer(out) ? out : Buffer.from(out as Uint8Array)
  );
}

/** Remove a previously generated deck file before regenerating. */
function removeOldFile(fileUrl: string | null | undefined) {
  if (!fileUrl?.startsWith("/uploads/")) return;
  try {
    fs.unlinkSync(resolveUploadPath(fileUrl.replace("/uploads/", "")));
  } catch {
    // Already gone.
  }
}

export async function getPresentation(userId: number, documentId: number) {
  await assertAccess(userId, documentId);
  const row = await queries.getGeneratedSlides(documentId);
  return {
    presentation: row ?? null,
    generating: inFlight.has(documentId),
  };
}

async function buildPresentation(
  documentId: number,
  userId: number,
  slideCount: number,
  topic?: string
) {
  const doc = await documentAi.ensureDocumentText(documentId);
  documentAi.assertDocumentHasExtractedText(doc);
  const deck = await generateSlideDeck(
    documentId,
    doc.extractedText || "",
    doc.title,
    slideCount,
    topic
  );

  const key = `presentations/doc-${documentId}-${Date.now()}.pptx`;
  const file = resolveUploadPath(key);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const buffer = await buildPptxBuffer(deck);
  await fs.promises.writeFile(file, buffer);

  // Drop the previous file now that the new one is safely on disk.
  const existing = await queries.getGeneratedSlides(documentId);
  if (existing) removeOldFile(existing.fileUrl);

  return queries.replaceGeneratedSlides({
    documentId,
    createdBy: userId,
    title: deck.title,
    subtitle: deck.subtitle ?? null,
    slideCount: deck.slides.length,
    slides: deck.slides,
    fileUrl: `/uploads/${key}`,
    fileKey: key,
    fileSize: buffer.length,
  });
}

export async function generatePresentation(
  userId: number,
  documentId: number,
  slideCount: number,
  topic?: string
) {
  const doc = await assertAccess(userId, documentId);
  const flags = await getFeatureFlags();
  if (!flags.presentationGeneration) {
    throw new TRPCError({
      code: "PRECONDITION_FAILED",
      message: "Presentation generation is turned off by an administrator.",
    });
  }
  let job = inFlight.get(documentId);
  if (!job) {
    job = buildPresentation(documentId, userId, slideCount, topic).finally(() =>
      inFlight.delete(documentId)
    );
    inFlight.set(documentId, job);
  }
  return job;
}
