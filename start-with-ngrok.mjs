/**
 * update-mobile-url.mjs
 *
 * Reads the active ngrok tunnel URL from the ngrok local API
 * and writes it to mobile/.env automatically.
 *
 * Usage (after ngrok is already running):
 *   node start-with-ngrok.mjs
 *   - or -
 *   pnpm dev:ngrok
 */

import { writeFileSync } from "fs";

async function getAndSaveNgrokUrl() {
  try {
    const res = await fetch("http://127.0.0.1:4040/api/tunnels");
    if (!res.ok) throw new Error("ngrok API not responding");

    const data = await res.json();
    const tunnel = data.tunnels?.find((t) => t.proto === "https");

    if (!tunnel) {
      console.error("❌ No active ngrok HTTPS tunnel found.");
      console.error("   Make sure ngrok is running: ngrok http 3000");
      process.exit(1);
    }

    const url = tunnel.public_url;

    writeFileSync(
      "mobile/.env",
      `# Auto-generated by dev:ngrok — do not edit manually\nEXPO_PUBLIC_API_URL=${url}\n`,
      "utf-8"
    );

    console.log("✅ mobile/.env updated:");
    console.log("   EXPO_PUBLIC_API_URL =", url);
    console.log("\n📱 Now reload Metro: press r in the Metro terminal.");
  } catch {
    console.error("❌ Could not read ngrok API at http://127.0.0.1:4040");
    console.error("   Start ngrok first in a separate terminal:");
    console.error("   ngrok http 3000");
  }
}

getAndSaveNgrokUrl();
