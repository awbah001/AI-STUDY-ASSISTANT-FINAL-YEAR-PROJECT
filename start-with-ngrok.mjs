/**
 * start-with-ngrok.mjs
 *
 * Starts the Cognify backend server and opens an ngrok tunnel.
 * Automatically writes the public URL to mobile/.env so the
 * mobile app connects without any manual IP configuration.
 *
 * Usage:
 *   node start-with-ngrok.mjs
 *
 * Prerequisites:
 *   1. npm install -g ngrok
 *   2. ngrok config add-authtoken YOUR_TOKEN  (one-time setup)
 *   3. In a SECOND terminal: cd mobile && npx expo start --tunnel --clear
 */

import { spawn, exec } from "child_process";
import { writeFileSync } from "fs";
import { promisify } from "util";

const execAsync = promisify(exec);

const PORT = process.env.PORT || 3000;

// ── 1. Start the backend server ───────────────────────────────────────────────
console.log("🚀 Starting Cognify server on port", PORT, "...");

const server = spawn("node", ["--loader", "tsx/esm", "server/_core/index.ts"], {
  env: { ...process.env, NODE_ENV: "development" },
  stdio: "inherit",
  shell: true,
});

server.on("error", (err) => {
  console.error("❌ Server failed to start:", err.message);
  process.exit(1);
});

// Wait for server to be ready
await new Promise((resolve) => setTimeout(resolve, 3000));

// ── 2. Start ngrok tunnel ─────────────────────────────────────────────────────
console.log("🌐 Opening ngrok tunnel...");

try {
  // Try using ngrok npm package first
  let ngrokUrl;

  try {
    const ngrok = await import("ngrok");
    ngrokUrl = await ngrok.connect(Number(PORT));
  } catch {
    // Fall back to CLI
    console.log("Using ngrok CLI...");
    const { stdout } = await execAsync(
      `ngrok http ${PORT} --log=stdout --log-level=info &`
    );

    // Wait for ngrok to start
    await new Promise((r) => setTimeout(r, 3000));

    // Fetch URL from ngrok API
    const res = await fetch("http://127.0.0.1:4040/api/tunnels");
    const data = await res.json();
    ngrokUrl = data.tunnels?.find((t) => t.proto === "https")?.public_url;
  }

  if (!ngrokUrl) {
    throw new Error("Could not get ngrok public URL");
  }

  console.log("\n✅ ngrok tunnel active:");
  console.log("   Public URL:", ngrokUrl);

  // ── 3. Update mobile/.env automatically ──────────────────────────────────
  const envContent = `# Auto-generated by start-with-ngrok.mjs — do not edit manually
# Regenerated every time you run: node start-with-ngrok.mjs
EXPO_PUBLIC_API_URL=${ngrokUrl}
`;
  writeFileSync("mobile/.env", envContent, "utf-8");
  console.log("   ✅ mobile/.env updated with new URL");

  console.log("\n──────────────────────────────────────────────");
  console.log("📱 Now in a SECOND terminal run:");
  console.log("   cd mobile && npx expo start --tunnel --clear");
  console.log("");
  console.log("   The mobile app will automatically use:");
  console.log("  ", ngrokUrl);
  console.log("──────────────────────────────────────────────\n");
} catch (err) {
  console.error("\n❌ ngrok failed:", err.message);
  console.error("Make sure ngrok is installed and authenticated:");
  console.error("  npm install -g ngrok");
  console.error("  ngrok config add-authtoken YOUR_TOKEN");
  console.error("\nAlternatively, run ngrok manually:");
  console.error(`  ngrok http ${PORT}`);
  console.error("Then update mobile/.env with the HTTPS URL.");
}

// Keep server running
process.on("SIGINT", () => {
  console.log("\nShutting down...");
  server.kill();
  process.exit(0);
});
