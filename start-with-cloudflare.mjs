/**
 * start-with-cloudflare.mjs
 *
 * Starts a Cloudflare Quick Tunnel (no account required) pointing at
 * the local dev server on port 3000, then writes the public HTTPS URL
 * to mobile/.env so the Expo app picks it up automatically.
 *
 * Prerequisites:
 *   Install cloudflared:
 *     winget install --id Cloudflare.cloudflared
 *   …or download the binary from:
 *     https://developers.cloudflare.com/cloudflare-one/connections/connect-networks/downloads/
 *
 * Usage:
 *   node start-with-cloudflare.mjs
 *   - or -
 *   pnpm dev:tunnel
 *
 * The script:
 *   1. Spawns `cloudflared tunnel --url http://localhost:3000`
 *   2. Parses the randomly assigned trycloudflare.com URL from its output
 *   3. Writes EXPO_PUBLIC_API_URL to mobile/.env
 *   4. Keeps running so the tunnel stays alive (Ctrl+C to stop)
 */

import { spawn } from "child_process";
import { writeFileSync } from "fs";

function writeMobileEnv(url) {
  writeFileSync(
    "mobile/.env",
    `# Auto-generated by dev:tunnel — do not edit manually\nEXPO_PUBLIC_API_URL=${url}\n`,
    "utf-8"
  );
  console.log("\n✅ mobile/.env updated:");
  console.log("   EXPO_PUBLIC_API_URL =", url);
  console.log("\n📱 Now reload Metro: press r in the Metro terminal.");
  console.log("🌐 Web app: add VITE_API_URL=" + url + " to .env and rebuild.");
  console.log("\n🔒 Tunnel is live — keep this terminal open. Ctrl+C to stop.\n");
}

const child = spawn(
  "cloudflared",
  ["tunnel", "--url", "http://localhost:3000"],
  { stdio: ["ignore", "pipe", "pipe"] }
);

let urlFound = false;

function parseLine(line) {
  if (urlFound) return;
  // cloudflared prints the URL in its stderr output
  const match = line.match(/https:\/\/[a-z0-9\-]+\.trycloudflare\.com/);
  if (match) {
    urlFound = true;
    writeMobileEnv(match[0]);
  }
}

child.stdout.on("data", (d) => {
  const text = d.toString();
  process.stdout.write(text);
  text.split("\n").forEach(parseLine);
});

child.stderr.on("data", (d) => {
  const text = d.toString();
  process.stderr.write(text);
  text.split("\n").forEach(parseLine);
});

child.on("close", (code) => {
  console.log(`\ncloudflared exited with code ${code}`);
  process.exit(code ?? 0);
});

child.on("error", (err) => {
  if (err.code === "ENOENT") {
    console.error("❌ cloudflared not found. Install it first:");
    console.error("   winget install --id Cloudflare.cloudflared");
    console.error("   Or download from: https://developers.cloudflare.com/cloudflare-one/connections/connect-networks/downloads/");
  } else {
    console.error("❌ Failed to start cloudflared:", err.message);
  }
  process.exit(1);
});

// Keep the process alive (tunnel dies when this process exits)
process.on("SIGINT", () => {
  console.log("\n🛑 Stopping tunnel...");
  child.kill();
  process.exit(0);
});
